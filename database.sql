create extension if not exists pgcrypto;

-- PERFIS PÚBLICOS (as senhas ficam no Supabase Auth e NÃO nesta tabela)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null check (char_length(username) between 3 and 24),
  avatar_url text,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

-- MATÉRIAS
create table if not exists public.posts (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  title text not null check (char_length(title) between 3 and 180),
  category text not null,
  author text not null default 'Redação Lógicas PXG',
  summary text not null check (char_length(summary) <= 360),
  content text not null,
  score smallint not null default 0 check (score between 0 and 100),
  icon text not null default '📰',
  cover text not null default 'dark' check (cover in ('red','yellow','blue','purple','green','dark')),
  cover_image_url text,
  featured boolean not null default false,
  published boolean not null default true,
  published_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- UMA REAÇÃO POR USUÁRIO EM CADA MATÉRIA (Curtir OU Amei)
create table if not exists public.reactions (
  post_id uuid not null references public.posts(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  reaction text not null check (reaction in ('like','love','funny')),
  created_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

-- COMENTÁRIOS
create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  post_id uuid not null references public.posts(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  content text not null check (char_length(trim(content)) between 1 and 800),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists profiles_username_unique_ci on public.profiles ((lower(trim(username))));
create index if not exists idx_posts_published_at on public.posts(published_at desc);
create index if not exists idx_comments_post_id on public.comments(post_id, created_at desc);
create index if not exists idx_reactions_post_id on public.reactions(post_id);

-- Cria o perfil público automaticamente quando uma conta nasce no Auth.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, username)
  values (
    new.id,
    left(coalesce(nullif(trim(new.raw_user_meta_data ->> 'username'), ''), split_part(coalesce(new.email, 'usuario'), '@', 1), 'usuario'), 24)
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Timestamp automático para alterações.
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end;
$$;
drop trigger if exists posts_set_updated_at on public.posts;
create trigger posts_set_updated_at before update on public.posts for each row execute procedure public.set_updated_at();
drop trigger if exists comments_set_updated_at on public.comments;
create trigger comments_set_updated_at before update on public.comments for each row execute procedure public.set_updated_at();

-- Função central de autorização administrativa.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- Validação pública de disponibilidade do nome (a UNIQUE continua sendo a proteção definitiva).
create or replace function public.username_available(candidate text)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select not exists (
    select 1 from public.profiles
    where lower(trim(username)) = lower(trim(candidate))
  );
$$;
revoke all on function public.username_available(text) from public;
grant execute on function public.username_available(text) to anon, authenticated;

-- Nunca permite que um usuário comum altere role; admins podem alterar outros usuários.
create or replace function public.protect_profile_role()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if new.role is distinct from old.role and auth.uid() is not null then
    if auth.uid() = old.id then
      raise exception 'Sua própria função não pode ser alterada por esta interface.';
    end if;
    if not public.is_admin() then
      raise exception 'Somente administradores podem alterar funções.';
    end if;
  end if;
  return new;
end;
$$;
drop trigger if exists profiles_protect_role on public.profiles;
create trigger profiles_protect_role before update on public.profiles for each row execute procedure public.protect_profile_role();

