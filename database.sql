-- PERFIS: nomes são públicos; cada usuário pode alterar apenas seus campos editáveis.
drop policy if exists "profiles_public_read" on public.profiles;
create policy "profiles_public_read" on public.profiles for select to anon, authenticated using (true);
drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);
drop policy if exists "profiles_admin_update" on public.profiles;
create policy "profiles_admin_update" on public.profiles for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- POSTS: público só lê publicados; admin controla tudo.
drop policy if exists "posts_public_read" on public.posts;
create policy "posts_public_read" on public.posts for select to anon, authenticated using (published = true or public.is_admin());
drop policy if exists "posts_admin_insert" on public.posts;
create policy "posts_admin_insert" on public.posts for insert to authenticated with check (public.is_admin());
drop policy if exists "posts_admin_update" on public.posts;
create policy "posts_admin_update" on public.posts for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "posts_admin_delete" on public.posts;
create policy "posts_admin_delete" on public.posts for delete to authenticated using (public.is_admin());

-- REAÇÕES: todos leem contagens; usuário autenticado controla apenas a própria reação.
drop policy if exists "reactions_public_read" on public.reactions;
create policy "reactions_public_read" on public.reactions for select to anon, authenticated using (true);
drop policy if exists "reactions_insert_own" on public.reactions;
